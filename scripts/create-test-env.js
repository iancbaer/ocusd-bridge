const fs = require("fs");
const crypto = require("crypto");
const { ethers } = require("ethers");
const nacl = require("tweetnacl");

const BASE58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";

function base58Encode(bytes) {
  let zeroes = 0;
  while (zeroes < bytes.length && bytes[zeroes] === 0) zeroes += 1;

  let source = Array.from(bytes);
  let result = "";

  while (source.length > 0) {
    let carry = 0;
    const next = [];
    for (const byte of source) {
      const value = carry * 256 + byte;
      const digit = Math.floor(value / 58);
      carry = value % 58;
      if (next.length > 0 || digit > 0) next.push(digit);
    }
    result += BASE58[carry];
    source = next;
  }

  for (let i = 0; i < zeroes; i += 1) result += "1";
  return result.split("").reverse().join("");
}

function octraAddress(publicKey) {
  const digest = crypto.createHash("sha256").update(Buffer.from(publicKey)).digest();
  let encoded = base58Encode(digest);
  while (encoded.length < 44) encoded = `1${encoded}`;
  return `oct${encoded}`;
}

function main() {
  const envPath = ".env";
  if (fs.existsSync(envPath) && !process.argv.includes("--force")) {
    throw new Error(".env already exists. Use --force to overwrite it.");
  }

  const deployer = ethers.Wallet.createRandom();
  const ethRelayer = ethers.Wallet.createRandom();
  const owner = ethers.Wallet.createRandom();
  const octraSeed = crypto.randomBytes(32);
  const octraKeypair = nacl.sign.keyPair.fromSeed(octraSeed);
  const octraPrivB64 = Buffer.from(octraSeed).toString("base64");
  const octraAddr = octraAddress(octraKeypair.publicKey);

  const content = `# Generated by scripts/create-test-env.js.
# Keep this file private. It contains live private keys once funded.

# Paste a Sepolia RPC URL from Alchemy or Infura.
ETH_RPC_URL=

# Ethereum deployment/test keys.
DEPLOYER_PRIVATE_KEY=${deployer.privateKey}
RELAYER_PRIVATE_KEY_ETH=${ethRelayer.privateKey}
RELAYER_SIGNER_ADDRESS=${ethRelayer.address}
INITIAL_OWNER_ADDRESS=${owner.address}

# Filled after deployment.
ETH_CUSTODY_CONTRACT=
USDT_ADDRESS=

# Paste your Octra RPC endpoint. It must accept JSON-RPC POST /rpc.
OCTRA_RPC_URL=
OCTRA_TOKEN_CONTRACT=
RELAYER_OCTRA_ADDRESS=${octraAddr}
RELAYER_PRIVATE_KEY_OCTRA=${octraPrivB64}

POLL_INTERVAL_MS=3000
CONFIRMATIONS_REQUIRED=2
RELAYER_DB_PATH=relayer.sqlite
OCTRA_CALL_FEE=1000
PROOF_PORT=8080
`;

  fs.writeFileSync(envPath, content, { mode: 0o600 });

  console.log(".env created with fresh local keys.");
  console.log(`Fund Sepolia deployer: ${deployer.address}`);
  console.log(`Fund/register Octra relayer: ${octraAddr}`);
  console.log("Paste ETH_RPC_URL and OCTRA_RPC_URL before deploying.");
}

main();
